export function getNearestChromaColorIndex(r: number, g: number, b: number): number {
    let minDistance = Infinity;
    let closestIndex = 0;
    for (let i = 0; i < CHROMA_DEPTH_PALETTE.length; i++) {
        const p = CHROMA_DEPTH_PALETTE[i];
        const dist = Math.pow(r - p.r, 2) + Math.pow(g - p.g, 2) + Math.pow(b - p.b, 2);
        if (dist < minDistance) {
            minDistance = dist;
            closestIndex = i;
        }
    }
    return closestIndex;
}
